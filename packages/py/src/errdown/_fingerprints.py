def matches(fp: Dict[str, Any], status: int, h: Dict[str, str], body: str) -> bool:
    if fp["status"] and status not in fp["status"]:
        return False
    if fp["header"]:
        name, pat = fp["header"]
        v = h.get(name)
        if v is None or not pat.search(v):
            return False
    if fp["body"]:
        for rx in fp["body"]:
            if not rx.search(body):
                return False
    return bool(fp["header"] or fp["body"])


def find_fingerprint(lst: List[Dict[str, Any]], status: int, h: Dict[str, str], body: str) -> Optional[Dict[str, Any]]:
    for fp in lst:
        if matches(fp, status, h, body):
            return fp
    return None
